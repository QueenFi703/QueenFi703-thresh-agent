import { persistLocal } from "./persistence.js";
import { Octokit } from "@octokit/rest";
import type { RunContext, WorkflowAnalysis, PatchResult } from "../shared/types.js";
import { loadPatches } from "../patches/index.js";
import { perceive } from "./perception.js";
import { perceiveLocal } from "./local-runner.js";
import { buildWorkflowPlan } from "./workflow.js";

/**
 * agent/index.ts — Decision engine
 *
 * Orchestrates the detect → apply → commit/comment pipeline:
 *
 *   1. Perceive  — load workflow files (API or disk)
 *   2. Detect    — ask each registered patch whether it applies
 *   3. Apply     — collect PatchResults from applicable patches
 *   4. Act       — commit fixes via API / git, or leave a PR comment
 */

// ─── Helpers ──────────────────────────────────────────────────────────────────

export function formatReport(results: PatchResult[]): string {
  const lines = results.map(
    (r) =>
      `- **${r.patchId}**: ${r.summary}${r.outcome === "committed" ? " ✅ committed" : r.outcome === "approval-required" ? " ⚠️ approval required; no changes saved" : " ⚠️ proposed; no changes saved"}`
  );
  return [
    "## 🔧 Thresh — self-healing pipeline report",
    "",
    ...lines,
    "",
    "_Generated by [Thresh](https://github.com/QueenFi703/QueenFi703-thresh-agent)_",
  ].join("\n");

}

/** Post a PR comment listing all applied (or detected) patches. */
async function postComment(
  octokit: Octokit,
  owner: string,
  repo: string,
  prNumber: number,
  results: PatchResult[]
): Promise<void> {
  const body = formatReport(results);

  await octokit.issues.createComment({ owner, repo, issue_number: prNumber, body });
}

/** Commit a patched file via the GitHub Contents API. */
async function commitViaApi(
  octokit: Octokit,
  owner: string,
  repo: string,
  result: PatchResult,
  ref: string
): Promise<void> {
  await octokit.repos.createOrUpdateFileContents({
    owner,
    repo,
    path: result.path,
    message: `fix(thresh): ${result.summary}`,
    content: Buffer.from(result.content).toString("base64"),
    sha: result.sha,
    branch: ref,
  });
}

// ─── Core run function ────────────────────────────────────────────────────────

export interface AgentRunOptions {
  ctx: RunContext;
  owner: string;
  repo: string;
  /** Git ref / branch name — used for API commits and perception. */
  ref?: string;
}

/**
 * Entry point for both server (webhook) and local (composite Action) modes.
 *
 * Returns the list of PatchResults that were detected (regardless of whether
 * `commit` was set), so callers can log or surface them.
 */
export async function run(options: AgentRunOptions): Promise<PatchResult[]> {
  const { ctx, owner, repo, ref } = options;
  const octokit = new Octokit({ auth: ctx.token });

  // ── 1. Perceive ─────────────────────────────────────────────────────────────
  let analysis: WorkflowAnalysis;
  if (ctx.workspace) {
    // Local / composite Action mode — read from disk.
    analysis = perceiveLocal(owner, repo, ctx.workspace);
  } else {
    // Server / webhook mode — read via GitHub API.
    analysis = await perceive(ctx.token, owner, repo, ref);
  }

  if (analysis.workflows.length === 0) {
    console.log("[thresh] No workflow files found — nothing to do.");
    return [];
  }

  const workflowPlan = buildWorkflowPlan(analysis);
  console.log(
    `[thresh] Workflow plan: ${workflowPlan.incidentType} incident; planned MCP gateway ${workflowPlan.mcpGatewayUrl}`
  );
  if (workflowPlan.requiresApproval) {
    console.log("[thresh] Human approval required for consequential operations.");
  }

  // ── 2. Detect + Apply ───────────────────────────────────────────────────────
  const patches = await loadPatches();
  const results: PatchResult[] = [];

  for (const patch of patches) {
    // Each built-in returns one file; process every matching file once.
    for (const wf of [...analysis.workflows]) {
      const single = { ...analysis, workflows: [wf] };
      if (!patch.detect(single)) continue;
      const result = patch.apply(ctx, single);
      const approvalRequired = workflowPlan.requiresApproval || result.patchId === "github-actions/permissions";
      result.outcome = approvalRequired ? "approval-required" : "proposed";
      results.push(result);
      // Proposals must not influence subsequent changes to actual source.
      if (!ctx.commitFixes || !result.commit || approvalRequired) continue;
      if (ctx.workspace) continue; // Persist all eligible local results together below.
      if (!ref) throw new Error("A target branch is required before committing fixes.");
      await commitViaApi(octokit, owner, repo, result, ref);
      result.outcome = "committed";
      // Refresh the blob SHA after each API commit to avoid stale-SHA conflicts.
      analysis = await perceive(ctx.token, owner, repo, ref);
    }
  }

  const localResults = results.filter((r) => ctx.commitFixes && r.commit && r.outcome !== "approval-required");
  if (ctx.workspace && localResults.length > 0) {
    persistLocal(ctx.workspace, localResults, ref);
    for (const result of localResults) result.outcome = "committed";
  }

  // ── 4. Comment on PR (if applicable) ────────────────────────────────────────
  if (results.length > 0 && ctx.prNumber) {
    await postComment(octokit, owner, repo, ctx.prNumber, results);
  }

  if (results.length === 0) {
    console.log("[thresh] No applicable patches — workflows look healthy.");
  } else {
    console.log(`[thresh] Detected ${results.length} patch(es); ${results.filter((r) => r.outcome === "committed").length} committed.`);
  }

  return results;
}
